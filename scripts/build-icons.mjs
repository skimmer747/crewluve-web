// Copies the Phosphor "fill" path data this site uses into src/icons/iconPaths.ts.
// Run with `npm run icons` (installs @phosphor-icons/core on demand, never saved to package.json).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const fillDir = resolve(root, 'node_modules/@phosphor-icons/core/assets/fill')
const outFile = resolve(root, 'src/icons/iconPaths.ts')

// Component name -> Phosphor file stem. The first block maps the SF Symbols Crewluve uses on these
// cards (spec §4.1); the second maps AirlineBranding's airline symbols (spec §6.10).
const ICONS = {
  House: 'house', Airplane: 'airplane', Car: 'car', ArrowsClockwise: 'arrows-clockwise', Bed: 'bed',
  Buildings: 'buildings', ClockCountdown: 'clock-countdown', Lightning: 'lightning', BookOpen: 'book-open',
  MapPin: 'map-pin', Circle: 'circle', Package: 'package', AirplaneTakeoff: 'airplane-takeoff',
  AirplaneLanding: 'airplane-landing', Cloud: 'cloud', ArrowCircleUp: 'arrow-circle-up', Warning: 'warning',
  ArrowClockwise: 'arrow-clockwise', SignOut: 'sign-out', Heart: 'heart',

  Triangle: 'triangle', Star: 'star', GlobeHemisphereWest: 'globe-hemisphere-west', AirplaneTilt: 'airplane-tilt',
  Mountains: 'mountains', CurrencyCircleDollar: 'currency-circle-dollar', Leaf: 'leaf', Sun: 'sun', Wind: 'wind',
  Bird: 'bird', Crown: 'crown', Rabbit: 'rabbit', Sparkle: 'sparkle', CircleHalf: 'circle-half',
  GlobeHemisphereEast: 'globe-hemisphere-east', Diamond: 'diamond', Plus: 'plus', CaretUpDown: 'caret-up-down',
  Sailboat: 'sailboat', PawPrint: 'paw-print', NavigationArrow: 'navigation-arrow',
}

const lines = []
for (const [name, stem] of Object.entries(ICONS)) {
  const svg = readFileSync(resolve(fillDir, `${stem}-fill.svg`), 'utf8')
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1])
  if (paths.length === 0 || /<(rect|circle|ellipse|line|polyline|polygon)\b/.test(svg)) {
    throw new Error(`${stem}-fill.svg is not plain path data`)
  }
  lines.push(`  ${name}: ${JSON.stringify(paths)},`)
}

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(
  outFile,
  `// GENERATED by scripts/build-icons.mjs from @phosphor-icons/core 2.1.1 (MIT), "fill" weight, 256×256.
// Do not edit by hand; run \`npm run icons\`.
export const ICON_PATHS = {
${lines.join('\n')}
} as const

export type IconName = keyof typeof ICON_PATHS
`,
)
console.log(`wrote ${lines.length} icons to ${outFile}`)

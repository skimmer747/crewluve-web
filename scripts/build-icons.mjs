// Copies the Phosphor "fill" path data this site uses into src/icons/iconPaths.ts.
// Run with `npm run icons` (installs @phosphor-icons/core on demand, never saved to package.json).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const phosphorDir = resolve(root, 'node_modules/@phosphor-icons/core')
const fillDir = resolve(phosphorDir, 'assets/fill')
const outFile = resolve(root, 'src/icons/iconPaths.ts')
const { version } = JSON.parse(readFileSync(resolve(phosphorDir, 'package.json'), 'utf8'))

// Component name -> Phosphor file stem. The first block maps the SF Symbols Crewluve uses on these
// cards (spec §4.1, and the slice 2A trip cards); the second maps AirlineBranding's airline symbols (spec §6.10);
// the third adds the weather and sun dial symbols of the slice 2B1 location card; the fourth, the slice 2B2 sun popup's.
const ICONS = {
  House: 'house', Airplane: 'airplane', Car: 'car', ArrowsClockwise: 'arrows-clockwise', Bed: 'bed',
  Buildings: 'buildings', ClockCountdown: 'clock-countdown', Lightning: 'lightning', BookOpen: 'book-open',
  MapPin: 'map-pin', Circle: 'circle', Package: 'package', AirplaneTakeoff: 'airplane-takeoff',
  AirplaneLanding: 'airplane-landing', Cloud: 'cloud', ArrowCircleUp: 'arrow-circle-up', Warning: 'warning',
  ArrowClockwise: 'arrow-clockwise', SignOut: 'sign-out', Heart: 'heart', CalendarBlank: 'calendar-blank', Clock: 'clock',

  Triangle: 'triangle', Star: 'star', GlobeHemisphereWest: 'globe-hemisphere-west', AirplaneTilt: 'airplane-tilt',
  Mountains: 'mountains', CurrencyCircleDollar: 'currency-circle-dollar', Leaf: 'leaf', Sun: 'sun', Wind: 'wind',
  Bird: 'bird', Crown: 'crown', Rabbit: 'rabbit', Sparkle: 'sparkle', CircleHalf: 'circle-half',
  GlobeHemisphereEast: 'globe-hemisphere-east', Diamond: 'diamond', Plus: 'plus', CaretUpDown: 'caret-up-down',
  Sailboat: 'sailboat', PawPrint: 'paw-print', NavigationArrow: 'navigation-arrow',

  Moon: 'moon', CloudSun: 'cloud-sun', CloudMoon: 'cloud-moon', CloudFog: 'cloud-fog', CloudRain: 'cloud-rain',
  CloudSnow: 'cloud-snow', CloudLightning: 'cloud-lightning',

  XCircle: 'x-circle', SunHorizon: 'sun-horizon', MapPinArea: 'map-pin-area',
}

const lines = []
for (const [name, stem] of Object.entries(ICONS)) {
  const file = `${stem}-fill.svg`
  const svg = readFileSync(resolve(fillDir, file), 'utf8')
  // The icon components draw every path in a 256x256 box with no per-path styling, so refuse anything else.
  const viewBox = svg.match(/<svg\b[^>]*\sviewBox="([^"]*)"/)?.[1]
  if (viewBox !== '0 0 256 256') throw new Error(`${file} has viewBox ${JSON.stringify(viewBox)}, expected "0 0 256 256"`)
  const paths = []
  for (const [, tag] of svg.matchAll(/<path\b([^>]*)>/g)) {
    const attributes = [...tag.matchAll(/([\w:-]+)\s*=\s*"([^"]*)"/g)]
    if (attributes.length !== 1 || attributes[0][1] !== 'd') {
      throw new Error(`${file} has a <path> with attributes other than d: ${tag.trim()}`)
    }
    paths.push(attributes[0][2])
  }
  if (paths.length === 0 || /<(rect|circle|ellipse|line|polyline|polygon)\b/.test(svg)) {
    throw new Error(`${file} is not plain path data`)
  }
  lines.push(`  ${name}: ${JSON.stringify(paths)},`)
}

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(
  outFile,
  `// GENERATED by scripts/build-icons.mjs from @phosphor-icons/core ${version} (MIT), "fill" weight, 256×256.
// Do not edit by hand; run \`npm run icons\`.
export const ICON_PATHS = {
${lines.join('\n')}
} as const

export type IconName = keyof typeof ICON_PATHS
`,
)
console.log(`wrote ${lines.length} icons to ${outFile}`)
